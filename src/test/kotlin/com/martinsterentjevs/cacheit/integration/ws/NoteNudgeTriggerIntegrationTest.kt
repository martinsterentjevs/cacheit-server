                    it.noteId == note.noteId
            }

        assertEquals(WsNudgeType.NOTE_DELETED, nudge.type)
        assertEquals(note.noteId, nudge.noteId)
    }

    @Test
    fun `acquireDrawingLock triggers NOTE_LOCK_ACQUIRED nudge with correct device id`() {
        val user = registerAndLogin(restTemplate, tokenService)
        val (_, received) =
            connectAndCaptureNudges(user.accessToken)

        val note =
            noteService.addNote(
                noteDto(user.userId),
                "Bearer ${user.accessToken}"
            )

        val mark = received.mark()

        noteService.acquireDrawingLock(
            note.noteId,
