                it.type == WsNudgeType.NOTE_LOCK_ACQUIRED &&
                    it.noteId == note.noteId
            }

        assertEquals(WsNudgeType.NOTE_LOCK_ACQUIRED, nudge.type)
        assertEquals(user.deviceId, nudge.lockedByDeviceId)
    }

    @Test
    fun `restoreVersion triggers NOTE_RESTORED nudge after commit`() {
        val user = registerAndLogin(restTemplate, tokenService)
        val (_, received) =
            connectAndCaptureNudges(user.accessToken)

        val note =
            noteService.addNote(
                noteDto(
                    user.userId,
                    title = "v1"
                ),
                "Bearer ${user.accessToken}"
            )

        val versions =
            noteService.getVersionHistory(
                note.noteId,
                "Bearer ${user.accessToken}"
            )

        val originalVersionId =
            versions.first().versionId

        noteService.updateNote(
            note.copy(encTitle = "v2"),
            "Bearer ${user.accessToken}"
        )

        /*
         * Mark the point after all setup operations.
         *
         * Any NOTE_UPDATED nudges generated by setup are irrelevant.
         * We do not clear the list because an earlier WebSocket delivery
         * could still be in flight.
         */
        val mark = received.mark()

        noteService.restoreVersion(
            note.noteId,
            originalVersionId,
            "Bearer ${user.accessToken}"
        )

        val nudge =
            received.awaitNudge(mark) {
                it.type == WsNudgeType.NOTE_RESTORED &&
                    it.noteId == note.noteId
            }

        assertEquals(WsNudgeType.NOTE_RESTORED, nudge.type)
        assertEquals(note.noteId, nudge.noteId)
    }

    @Test
    fun `releaseDrawingLock triggers NOTE_LOCK_RELEASED nudge after commit`() {
        val user = registerAndLogin(restTemplate, tokenService)
