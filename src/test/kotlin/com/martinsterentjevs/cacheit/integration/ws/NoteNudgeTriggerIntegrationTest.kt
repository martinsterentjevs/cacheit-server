package com.martinsterentjevs.cacheit.integration.ws

import com.martinsterentjevs.cacheit.dtos.note.NoteDto
import com.martinsterentjevs.cacheit.dtos.websockets.WsNudgeType
import com.martinsterentjevs.cacheit.services.NoteService
import com.martinsterentjevs.cacheit.services.TokenService
import com.martinsterentjevs.cacheit.testdata.AuthTestHelper.registerAndLogin
import org.junit.jupiter.api.Test
import org.springframework.beans.factory.annotation.Autowired
import java.time.Instant
import java.util.UUID
import java.util.concurrent.TimeoutException
import kotlin.test.assertEquals
import kotlin.test.assertFailsWith

class NoteNudgeTriggerIntegrationTest : WsIntegrationTestBase() {
    @Autowired
    lateinit var tokenService: TokenService

    @Autowired
    lateinit var noteService: NoteService

    private fun noteDto(
        userId: UUID,
        title: String = "t",
        body: String = "b"
    ) = NoteDto(
        noteId = UUID.randomUUID(),
        userId = userId,
        lastModifiedAt = Instant.now(),
        isDeleted = false,
        hasHistory = false,
        encTitle = title,
        encBody = body,
        encDrawing = null,
        lockedByDeviceId = null,
        lockedAt = null
    )

    @Test
    fun `updateNote triggers NOTE_UPDATED nudge after commit`() {
        val user = registerAndLogin(restTemplate, tokenService)
        val (_, received) =
            connectAndCaptureNudges(user.accessToken)

        val note =
            noteService.addNote(
                noteDto(user.userId),
                "Bearer ${user.accessToken}"
            )

        val mark = received.mark()

        val updated =
            noteService.updateNote(
                note.copy(encTitle = "enc-title-v2"),
                "Bearer ${user.accessToken}"
            )

        val nudge =
            received.awaitNudge(mark) {
                it.type == WsNudgeType.NOTE_UPDATED &&
                    it.noteId == updated.noteId
            }

        assertEquals(WsNudgeType.NOTE_UPDATED, nudge.type)
        assertEquals(updated.noteId, nudge.noteId)
    }

    @Test
    fun `deleteNote triggers NOTE_DELETED nudge after commit`() {
        val user = registerAndLogin(restTemplate, tokenService)
        val (_, received) =
            connectAndCaptureNudges(user.accessToken)

