        )

        val mark = received.mark()

        noteService.releaseDrawingLock(
            note.noteId,
            "Bearer ${user.accessToken}"
        )

        val nudge =
            received.awaitNudge(mark) {
                it.type == WsNudgeType.NOTE_LOCK_RELEASED &&
                    it.noteId == note.noteId
            }

        assertEquals(WsNudgeType.NOTE_LOCK_RELEASED, nudge.type)
        assertEquals(note.noteId, nudge.noteId)
    }

    @Test
    fun `getNotes does not trigger a nudge`() {
        val user = registerAndLogin(restTemplate, tokenService)
        val (_, received) =
            connectAndCaptureNudges(user.accessToken)

        val note =
            noteService.addNote(
                noteDto(user.userId),
                "Bearer ${user.accessToken}"
            )

        /*
         * addNote does not have an event listener-backed nudge assertion
         * here, so establish the boundary immediately before getNotes().
         */
        val mark = received.mark()

        noteService.getNotes(
            "Bearer ${user.accessToken}"
        )

        val deadline =
            System.nanoTime() +
                java.util.concurrent.TimeUnit.SECONDS
                    .toNanos(2)

        while (System.nanoTime() < deadline) {
            val unexpected =
                received
                    .snapshot()
                    .drop(mark)
                    .firstOrNull()

            if (unexpected != null) {
                throw AssertionError(
                    "getNotes produced an unexpected nudge: $unexpected"
                )
            }

            Thread.sleep(10)
        }

        // Keep the note variable meaningful as setup verification.
        assertEquals(note.userId, user.userId)
    }

    @Test
    fun `nudge for one user is never delivered to another users session`() {
        val userA = registerAndLogin(restTemplate, tokenService)
        val userB = registerAndLogin(restTemplate, tokenService)

        val (_, receivedA) =
            connectAndCaptureNudges(userA.accessToken)

        val (_, receivedB) =
            connectAndCaptureNudges(userB.accessToken)

        val noteA =
            noteService.addNote(
                noteDto(userA.userId, title = "a"),
                "Bearer ${userA.accessToken}"
            )

        val markA = receivedA.mark()
        val markB = receivedB.mark()

        noteService.updateNote(
            noteA.copy(encTitle = "a2"),
            "Bearer ${userA.accessToken}"
        )

        val nudgeA =
            receivedA.awaitNudge(markA) {
                it.type == WsNudgeType.NOTE_UPDATED &&
                    it.noteId == noteA.noteId
            }

        assertEquals(noteA.noteId, nudgeA.noteId)

        /*
         * B has its own capture. Nothing generated for A should appear
         * after B's boundary.
         */
        assertFailsWith<TimeoutException> {
            receivedB.awaitNudge(markB) {
                it.type == WsNudgeType.NOTE_UPDATED &&
                    it.noteId == noteA.noteId
            }
        }
    }
}